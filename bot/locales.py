def t(lang: str, key: str, **kwargs) -> str:
    """Вернуть локализованную строку. Fallback → русский."""
    if lang not in SUPPORTED_LANGS:
        lang = DEFAULT_LANG
    entry = TEXTS.get(key, {})
    text = entry.get(lang) or entry.get(DEFAULT_LANG, key)
    if kwargs:
        return text.format(**kwargs)
    return text
